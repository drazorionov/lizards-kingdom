export function buildLevel(region) {
  if (region === 0) return buildForest();
  const l = layouts[region];
  const platforms = [
    ...l.ground.map(([x, w]) => ({
      x,
      y: 500,
      w,
      h: 130,
      ground: true,
      solid: true,
    })),
    ...l.upper.map(([x, y, w]) => ({
      x,
      y,
      w,
      h: 24,
      ground: false,
      solid: false,
    })),
  ];
  const [x, top, rightTop] = l.shaft;
  // Entry is below the left wall; alternate kicks through the open shaft to exit above.
  platforms.push(
    { x, y: top, w: 48, h: 360 - top, solid: true, wall: true },
    {
      x: x + 180,
      y: rightTop,
      w: 48,
      h: 500 - rightTop,
      solid: true,
      wall: true,
    },
  );
  // Short return ledge makes the wall-climb reward accessible from either direction.
  platforms.push({
    x: x + 50,
    y: top + 30,
    w: 125,
    h: 18,
    solid: false,
    ground: false,
  });
  platforms.forEach((p, id) => (p.id = id));
  return {
    platforms,
    tokens: l.tokens.map(([x, y]) => ({ x, y })),
    shaft: { x: x + 115, y: 470, top },
    title: l.title,
  };
}
