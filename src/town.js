export function residentProgress(n, p) {
  const g = growth(p),
    countType = (id) =>
      Object.values(p.tokens).filter((a) => a.includes(id)).length;
  const count =
    n.id === "rong"
      ? countType(2)
      : n.id === "gruk"
        ? p.defeated.length
        : n.id === "dar"
          ? p.visited.length
          : n.id === "sola"
            ? countType(1)
            : ["child", "stranger"].includes(n.id)
              ? g.secrets
              : g.flies;
  return {
    count,
    ready: count >= (n.need || 0),
    done: n.service
      ? p.services.includes(n.service)
      : n.quest
        ? p.quests.includes(n.quest)
        : false,
  };
}
