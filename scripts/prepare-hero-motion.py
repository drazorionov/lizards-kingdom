"""Pack reviewed artwork, never synthesize/interpolate poses or recolor pixels.

Calibrate each sheet to the standing body's scale; register hips independently
of changing tail/weapon bounds. Rendering calibration preserves that scale when
a wide attack needs extra space in its cell. All new cells retain alpha padding.
"""
from pathlib import Path
from PIL import Image
import importlib.util
import json
import statistics

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'art/characters/motion-v4'
OUT = ROOT / 'public/assets'
spec = importlib.util.spec_from_file_location('creature_packer', ROOT/'scripts/prepare-creatures.py')
packer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(packer)
CELL = 384
HIPS = {
 'quirel': {'run': [225,590,950,1300,1650,210,570,930,1290,1640],
            'attack': [250,760,270,760,270,760,285,785,280,775]},
 'urmasa': {'run': [255,610,960,1320,1660,245,600,960,1320,1680],
            'attack': [285,800,290,800,280,805,310,820,290,800]},
}

def build():
 metadata = {}
 calibration = {}
 for hero, legacy_count in [('quirel',24),('urmasa',16)]:
  key = f'hero-{hero}-painted'
  base = packer.pack(key, ROOT/f'art/characters/{hero}-painted-source.png', legacy_count, CELL, True)
  sheet = Image.new('RGBA',(CELL*4,CELL*11))
  with Image.open(OUT/base['atlas']) as legacy:
   sheet.alpha_composite(legacy.convert('RGBA'))
   standing_height = legacy.crop((0,0,CELL,CELL)).getbbox()[3] - legacy.crop((0,0,CELL,CELL)).getbbox()[1]
  frames = list(base['frames'])
  while len(frames)<24:
   frames.append({'rect':[(len(frames)%4)*CELL,(len(frames)//4)*CELL,CELL,CELL], 'reserved':True})
  calibration[hero] = {}
  for action, start, columns in [('run',24,5),('attack',34,2)]:
   path = SOURCE/f'{hero}-{action}.png'
   tiles = packer.extract(path,10,columns)
   # Guard against accidentally cutting artwork at a nominal grid boundary.
   assert len(tiles)==10
   packed_scale = min((CELL-24)/max(t.width for t,_ in tiles), (CELL-40)/max(t.height for t,_ in tiles))
   reference_height = statistics.median(t.height for t,_ in tiles) if action=='run' else statistics.mean([tiles[0][0].height,tiles[-1][0].height])
   desired_scale = standing_height/reference_height
   render_scale = desired_scale/packed_scale
   entries=[]
   for i,(tile,box) in enumerate(tiles):
    original=tile
    tile=tile.resize((round(tile.width*packed_scale),round(tile.height*packed_scale)),Image.Resampling.LANCZOS)
    x=(CELL-tile.width)//2; y=368-tile.height
    assert x>=10 and y>=10 and x+tile.width<=CELL-10
    cell=Image.new('RGBA',(CELL,CELL));cell.alpha_composite(tile,(x,y))
    bbox=cell.getbbox()
    assert bbox and min(bbox[:2])>=8 and bbox[2]<=CELL-8 and bbox[3]<=CELL-8
    index=start+i; rect=[(index%4)*CELL,(index//4)*CELL,CELL,CELL]
    sheet.alpha_composite(cell,(rect[0],rect[1]))
    # Match the existing standing hip's displacement from the player center.
    hip_offset=32 if hero=='quirel' else 46
    anchor_x=x+(HIPS[hero][action][i]-box[0])*packed_scale-hip_offset/render_scale
    entry={'anchorX':round(anchor_x,3),'scale':round(render_scale,5)}
    entries.append(entry)
    frames.append({'rect':rect,'source':str(path.relative_to(ROOT)), 'sourceBounds':list(box),'hipX':HIPS[hero][action][i], 'paddingBounds':list(bbox),**entry})
   calibration[hero][action]=entries
  sheet.save(OUT/base['atlas'],'WEBP',lossless=True,method=6)
  metadata[hero]={**base,'version':4,'frames':frames,'sequences':{'run':list(range(24,34)),'attack':list(range(34,44))}}
  print(hero, '44 cells; 10 run + 10 attack poses;', round((OUT/base['atlas']).stat().st_size/1024), 'KiB')
 (OUT/'heroes-painted.json').write_text(json.dumps(metadata,indent=2)+'\n')
 (ROOT/'src/hero-motion-data.js').write_text('// Generated by scripts/prepare-hero-motion.py; registered artwork origins.\nexport const HERO_MOTION = '+json.dumps(calibration,indent=2)+';\n')

if __name__=='__main__':
 build()
