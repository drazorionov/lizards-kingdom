"""Pack ImageGen puppet parts and separate near/far knee-split leg artwork."""
from pathlib import Path
from collections import deque
from PIL import Image, ImageChops, ImageFilter
import json
ROOT=Path(__file__).resolve().parents[1]
CELL=512
PARTS=['body','thigh','shin','foot','tail','cape']
LANDMARKS={
 'quirel': {'body':[[400,510]], 'thigh':[[825,235],[870,550]], 'shin':[[1080,280],[1098,590]], 'foot':[[130,970]], 'tail':[[860,925]], 'cape':[[1185,772]]},
 'urmasa': {'body':[[405,570]], 'thigh':[[810,220],[858,663]], 'shin':[[1108,295],[1116,670]], 'foot':[[124,1020]], 'tail':[[805,915]], 'cape':[[1205,850]]},
}
SCALES={'quirel':{'body':.12,'foot':.045,'tail':.105,'cape':.10}, 'urmasa':{'body':.095,'foot':.052,'tail':.105,'cape':.13}}
LEG_LANDMARKS={
 'quirel': {
  'nearLeg': {'thigh':[[357,108],[393,383]], 'shin':[[752,173],[763,451]], 'foot':[[1143,385]]},
  'farLeg': {'thigh':[[360,588],[394,830]], 'shin':[[760,620],[770,926]], 'foot':[[1145,862]]},
 },
 'urmasa': {
  'nearLeg': {'thigh':[[312,123],[351,355]], 'shin':[[763,145],[763,435]], 'foot':[[1160,385]]},
  'farLeg': {'thigh':[[316,601],[359,827]], 'shin':[[773,620],[769,902]], 'foot':[[1160,858]]},
 },
}

def extract(path):
 im=Image.open(path).convert('RGBA');w,h=im.size;alpha=im.getchannel('A')
 mask=bytearray(alpha.point(lambda a:255 if a>40 else 0).tobytes());parts=[]
 for start in range(w*h):
  if not mask[start]:continue
  mask[start]=0;q=deque([start]);pixels=[];l,t,r,b=w,h,0,0
  while q:
   p=q.popleft();y,x=divmod(p,w);pixels.append(p);l=min(l,x);t=min(t,y);r=max(r,x);b=max(b,y)
   for n in (p-1 if x else -1,p+1 if x<w-1 else -1,p-w,p+w):
    if 0<=n<w*h and mask[n]:mask[n]=0;q.append(n)
  if len(pixels)>1500:parts.append((pixels,(l,t,r+1,b+1)))
 assert len(parts)==6, (path,len(parts),[(len(p),b) for p,b in parts])
 parts.sort(key=lambda p:(p[1][1]+p[1][3])/2)
 parts=[p for row in [parts[:3],parts[3:]] for p in sorted(row,key=lambda p:p[1][0])]
 for pixels,(l,t,r,b) in parts:
  box=(max(0,l-3),max(0,t-3),min(w,r+3),min(h,b+3));m=bytearray(w*h)
  for p in pixels:m[p]=255
  component=Image.frombytes('L',(w,h),bytes(m)).filter(ImageFilter.MaxFilter(5))
  tile=im.crop(box);tile.putalpha(ImageChops.multiply(alpha,component).crop(box))
  yield tile,box

def build():
 data={}
 for hero in ['quirel','urmasa']:
  sheet=Image.new('RGBA',(CELL*3,CELL*3));data[hero]={}
  originals=list(extract(ROOT/f'art/characters/walk-rig-v5/{hero}-parts.png'))
  entries=[(name,originals[PARTS.index(name)],LANDMARKS[hero][name],data[hero],SCALES[hero][name],1) for name in ['body','tail','cape']]
  leg_parts=list(extract(ROOT/f'art/characters/walk-rig-v5/{hero}-legs-v7.png'))
  for side_index,side in enumerate(['nearLeg','farLeg']):
   data[hero][side]={}
   for part_index,name in enumerate(['thigh','shin','foot']):
    tile,box=leg_parts[side_index*3+part_index]
    landmarks=LEG_LANDMARKS[hero][side][name]
    # Register the foot sole to the same ground anchor as the previous rig.
    foot_scale=(5.5 if hero=='quirel' else 6.8)/(box[3]-3-landmarks[0][1]) if name=='foot' else 1
    entries.append((name,(tile,box),landmarks,data[hero][side],foot_scale,.8 if name=='shin' else .85))
  for i,(name,(tile,box),landmarks,target,render_scale,width_scale) in enumerate(entries):
   scale=min(1,(CELL-24)/tile.width,(CELL-24)/tile.height)
   size=(round(tile.width*scale),round(tile.height*scale));tile=tile.resize(size,Image.Resampling.LANCZOS)
   x=i%3*CELL+12;y=i//3*CELL+12;sheet.alpha_composite(tile,(x,y))
   points=[[(p[0]-box[0])*scale,(p[1]-box[1])*scale] for p in landmarks]
   target[name]={'rect':[x,y,*size],'pivot':points[0]}
   if len(points)>1:
    target[name]['tip']=points[1]
    target[name]['widthScale']=width_scale
   else:target[name]['scale']=render_scale/scale
   print(hero,name,box,size)
  sheet.save(ROOT/f'public/assets/hero-{hero}-walk-rig-v5.webp','WEBP',lossless=True,method=6)
 (ROOT/'src/hero-rig-data.js').write_text('// Generated by scripts/prepare-hero-rig.py.\nexport const HERO_RIG_PARTS = '+json.dumps(data,indent=2)+';\n')
if __name__=='__main__':build()
